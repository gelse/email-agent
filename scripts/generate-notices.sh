#!/usr/bin/env bash
# Generate THIRD_PARTY_NOTICES.md from NuGet restore assets.
#
# Usage: scripts/generate-notices.sh <output-path>
#
# Scans every project.assets.json produced by `dotnet restore`, collects the
# direct + transitive package set, resolves license metadata from the NuGet
# package cache (via the nuspec for each package), and writes a deterministic
# markdown report. Packages whose nuspec carries no license metadata are listed
# in a trailing appendix instead of being silently dropped.
set -euo pipefail

out="${1:?usage: scripts/generate-notices.sh <output-path>}"

tmpdir="$(mktemp -d)"
trap 'rm -rf "$tmpdir"' EXIT

assets_list="$tmpdir/assets.txt"
folders_file="$tmpdir/folders.txt"
packages_file="$tmpdir/packages.txt"

find . -type f -name 'project.assets.json' -print > "$assets_list"

if [ ! -s "$assets_list" ]; then
    echo "generate-notices: no project.assets.json found (run dotnet restore first)" >&2
    exit 1
fi

# Collect the unique set of NuGet package cache folders referenced by the assets.
: > "$tmpdir/folders_raw.txt"
while IFS= read -r assets; do
    [ -z "$assets" ] && continue
    jq -r '.packageFolders | keys[]' "$assets" >> "$tmpdir/folders_raw.txt"
done < "$assets_list"
LC_ALL=C sort -u "$tmpdir/folders_raw.txt" > "$folders_file"

# Collect the unique package (id, version) set across all assets files.
: > "$tmpdir/packages_raw.txt"
while IFS= read -r assets; do
    [ -z "$assets" ] && continue
    jq -r '.libraries | to_entries[] | select(.value.type=="package") | .key' "$assets" >> "$tmpdir/packages_raw.txt"
done < "$assets_list"

# Convert "id/version" keys into tab-separated rows and de-duplicate.
sed 's#/#\t#' "$tmpdir/packages_raw.txt" | LC_ALL=C sort -u > "$packages_file"

license_for() {
    local id="$1" version="$2"
    local lc_id folder candidate nuspec lic
    lc_id="$(printf '%s' "$id" | tr '[:upper:]' '[:lower:]')"
    nuspec=""
    while IFS= read -r folder; do
        [ -z "$folder" ] && continue
        for candidate in "$folder/$lc_id/$version/$lc_id.nuspec" "$folder/$id/$version/$id.nuspec"; do
            if [ -f "$candidate" ]; then
                nuspec="$candidate"
                break 2
            fi
        done
    done < "$folders_file"

    if [ -z "$nuspec" ]; then
        printf 'NO LICENSE METADATA'
        return 0
    fi

    # Collapse the document to a single line so multi-line elements are matched,
    # and distinguish <license type="file"> from expression licenses so we never
    # report a filename as a license string.
    local flat lic_attrs lic_content
    flat="$(tr -d '\r' < "$nuspec" | tr '\n' ' ')"
    lic_attrs="$(printf '%s' "$flat" | sed -n 's/.*<license\([^>]*\)>[^<]*<\/license>.*/\1/p' | head -n 1)"
    lic_content="$(printf '%s' "$flat" | sed -n 's/.*<license[^>]*>\([^<]*\)<\/license>.*/\1/p' | head -n 1)"
    lic_content="$(printf '%s' "$lic_content" | sed 's/^[[:space:]]*//;s/[[:space:]]*$//')"
    if [ -n "$lic_content" ]; then
        case "$lic_attrs" in
            *type=\"file\"*)
                printf 'license file: %s' "$lic_content"
                ;;
            *)
                printf '%s' "$lic_content"
                ;;
        esac
        return 0
    fi
    lic="$(printf '%s' "$flat" | sed -n 's/.*<licenseUrl>\([^<]*\)<\/licenseUrl>.*/\1/p' | head -n 1)"
    lic="$(printf '%s' "$lic" | sed 's/^[[:space:]]*//;s/[[:space:]]*$//')"
    if [ -n "$lic" ]; then
        printf '%s' "$lic"
        return 0
    fi
    printf 'NO LICENSE METADATA'
}

main_file="$tmpdir/main.tsv"
appendix_file="$tmpdir/appendix.tsv"
: > "$main_file"
: > "$appendix_file"

while IFS=$'\t' read -r pkg_id pkg_version; do
    [ -z "$pkg_id" ] && continue
    lic="$(license_for "$pkg_id" "$pkg_version")"
    if [ "$lic" = "NO LICENSE METADATA" ]; then
        printf '%s\t%s\n' "$pkg_id" "$pkg_version" >> "$appendix_file"
    else
        printf '%s\t%s\t%s\n' "$pkg_id" "$pkg_version" "$lic" >> "$main_file"
    fi
done < "$packages_file"

# Sort deterministically (id, then version).
LC_ALL=C sort -t "$(printf '\t')" -k1,1 -k2,2 -o "$main_file" "$main_file"
LC_ALL=C sort -t "$(printf '\t')" -k1,1 -k2,2 -o "$appendix_file" "$appendix_file"

mkdir -p "$(dirname "$out")"

{
    echo "# Third-Party Notices"
    echo
    echo "This file is generated by \`scripts/generate-notices.sh\` from the NuGet"
    echo "restore assets (\`project.assets.json\`) and the license metadata in the"
    echo "NuGet package cache. Do not edit by hand."
    echo
    echo "## Packages"
    echo
    echo "| Package | Version | License |"
    echo "| --- | --- | --- |"
    if [ -s "$main_file" ]; then
        while IFS=$'\t' read -r pkg_id pkg_version lic; do
            echo "| $pkg_id | $pkg_version | $lic |"
        done < "$main_file"
    else
        echo "| (none) |  |  |"
    fi
    echo
    echo "## Packages without license metadata"
    echo
    if [ -s "$appendix_file" ]; then
        while IFS=$'\t' read -r pkg_id pkg_version; do
            echo "- $pkg_id $pkg_version"
        done < "$appendix_file"
    else
        echo "None."
    fi
    echo
} > "$out"
